// Copies the custom connector SVGs from the mobile app into the site so both
// render the same brand marks.
//
//   node scripts/sync-connector-icons.mjs [path-to-synced-mobile-app]
//
// Source: <app>/assets/icons/<connectorId>.svg (the same files the app's
// constants/connectorSvgIcons.ts loads). Output is committed, because the app
// repo isn't available where the site is built.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import os from "node:os";

const appDir = process.argv[2] ?? path.join(os.homedir(), "synced-mobile-app");
const iconsDir = path.join(appDir, "assets/icons");

// Site brand key -> app connector id. Only connectors that have a custom SVG in the
// app are listed; the rest use the same Phosphor duotone icon the app falls back to.
const MAP = { gmail: "gmail", groupme: "groupme", notion: "notion", onedrive: "onedrive", sms: "twilio" };

const out = {};
for (const [key, id] of Object.entries(MAP)) {
  const file = path.join(iconsDir, `${id}.svg`);
  if (!existsSync(file)) throw new Error(`Missing ${file}`);
  const svg = readFileSync(file, "utf8");
  const svgEmptyClips = new Set();
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${id}.svg has no viewBox`);
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    // Figma exports can carry an empty <clipPath>. react-native-svg ignores it,
    // but browsers clip the whole icon away (this is why OneDrive was blank).
    .replace(/<clipPath id="([^"]+)">\s*<\/clipPath>/g, (_, clipId) => `<!--empty:${clipId}-->`)
    .replace(/<!--empty:([^>]+)-->/g, (m, clipId) => {
      svgEmptyClips.add(clipId);
      return "";
    })
    .replace(/\s*clip-path="url\(#([^)]+)\)"/g, (m, clipId) => (svgEmptyClips.has(clipId) ? "" : m))
    .replace(/<defs>\s*<\/defs>/g, "")
    // Keep ids unique per icon so two icons on one page can't share a clipPath.
    .replace(/id="([^"]+)"/g, `id="${key}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${key}-$1)`)
    .replace(/\s+/g, " ")
    .trim();
  out[key] = { viewBox, inner };
}

const body = `// GENERATED by scripts/sync-connector-icons.mjs from synced-mobile-app/assets/icons. Do not edit by hand.
// Icons use currentColor, so the parent's CSS color sets the brand tint (as in the app).

export const CONNECTOR_SVGS: Record<string, { viewBox: string; inner: string }> = ${JSON.stringify(out, null, 2)};
`;
const dest = path.join(path.dirname(new URL(import.meta.url).pathname), "../app/components/connectorSvgs.generated.ts");
writeFileSync(dest, body);
console.log(`Wrote ${Object.keys(out).length} icons to ${path.relative(process.cwd(), dest)}`);
